def text_width(s):
    return sum(len(GLYPHS[ch][0]) + 1 for ch in s) - 1


def draw_text(img, s, x, y, col, shadow=None):
    for ch in s:
        g = GLYPHS[ch]
        for j, row in enumerate(g):
            for i, c in enumerate(row):
                if c == '#':
                    if shadow:
                        img.px(x + i, y + j + 1, shadow)
                    img.px(x + i, y + j, col)
        x += len(g[0]) + 1
